Breadth correlates with leadership: The highest-paying position (Associate Director – Data Insights at AT&T, $255.8k) required 13 distinct skills spanning big data (PySpark, Databricks), dual cloud stacks (AWS, Azure), and dual BI suites (Tableau, Power BI). In contrast, lower-paying entries focus strictly on a core statistical trifecta (SQL, Python, R).
